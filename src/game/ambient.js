/** 문장이 있는 type만 관찰 대상이 된다. */
export const LOOKABLE = new Set(Object.keys(LINES));

/**
 * 오늘 이 물건이 어떤 상태인가.
 *
 * @param {string} type
 * @param {number} day   게임 내 날짜. 같은 날은 같은 문장 — 다시 봐도 말이 안 바뀐다
 * @param {number|string} salt  같은 type이 방에 둘 이상일 때 갈라주는 값 (오브젝트 id).
 *   id는 `desk_1` 같은 문자열이라 그대로 더하면 문자열 연결이 되고 인덱스가 NaN이 된다.
 */
export function ambientLine(type, day = 1, salt = 0) {
  const pool = LINES[type];
  if (!pool?.length) return null;
  let n = 0;
  for (const ch of String(salt)) n = (n + ch.charCodeAt(0)) % 997;
  return pool[(Number(day) + n) % pool.length];
}

/**
 * 디렉터가 보낸 오늘의 관찰 문장으로 덮어쓴다.
 * TV에 뭐가 나오는지, 냉장고에 뭐가 들어왔는지는 **그날의 연출**이라 AI가 정하는 게 맞다.
 *
 * @param {Array<{type: string, line: string}>} list
 * @returns {Map<string, string>}
 */
export function ambientOverrides(list) {
  const m = new Map();
  for (const a of list ?? []) {
    if (typeof a?.type === 'string' && typeof a?.line === 'string' && a.line.trim()) {
      m.set(a.type, a.line.trim());
    }
  }
  return m;
}
